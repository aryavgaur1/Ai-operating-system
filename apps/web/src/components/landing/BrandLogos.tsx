export function BrandLogo({ name, className }: { name: string; className?: string }) {
  const Logo = BY_NAME[name.toLowerCase()];
  if (!Logo) {
    return (
      <span className={`inline-flex items-center justify-center rounded bg-white/10 text-[9px] font-semibold text-neutral-300 ${className || ''}`}>
        {name.slice(0, 2).toUpperCase()}
      </span>
    );
  }
  return <Logo className={className} />;
}
